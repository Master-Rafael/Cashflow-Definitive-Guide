export function startingCash(p: Profession) {
  return p.cashFlow + p.savings;
}

export function formatMoney(n: number) {
  const sign = n < 0 ? "−" : "";
  return `${sign}$${Math.abs(n).toLocaleString("en-US")}`;
}
